    public function getByName(string $Kbn): ?RecommendKbn
    {

        try {				
            $re = $this->createQueryBuilder('rk')				
                    
            ->where('rk.name = :name')				
            ->setParameter('name', $Kbn)				
            ->getQuery()				
            ->getSingleResult();				

