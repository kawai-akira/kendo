namespace Customize\Repository\Plugin;

#use Doctrine\ORM\QueryBuilder;
use Eccube\Entity\Product;
#use Eccube\Util\StringUtil;
#use Plugin\ProductReview42\Entity\ProductReview;
use Plugin\ProductReview42\Entity\ProductReviewStatus;
use Doctrine\Persistence\ManagerRegistry;

/**
 * ProductReview.
 *
 * This class was generated by the Doctrine ORM. Add your own custom
 * repository methods below.
 */
class ProductReviewRepository extends \Plugin\ProductReview42\Repository\ProductReviewRepository
{
    /**
     * ProductReviewRepository constructor.
     *
     * @param ManagerRegistry $registry
     */
    public function __construct(ManagerRegistry $registry)
    {
        parent::__construct($registry);
    }

    

    public function getProductReview(int $ProductId,int $Offset)
    {
        /** @var Product */
        $Product = $this->getEntityManager()->getRepository(Product::class)->find($ProductId);

            $qb = $this->createQueryBuilder('r')
            //    ->leftJoin('r.Product', 'p')
                ->where('r.Product = :Product')
                ->setParameter('Product', $Product)
                ->andWhere('r.recommend_level >=3 ')
                ->andWhere('r.Status = :Status')
                ->setParameter('Status', ProductReviewStatus::SHOW)
                ->setMaxResults($Offset)
                ->orderBy('r.create_date','DESC');

        return   $qb->getQuery()->getResult();

    }
}
